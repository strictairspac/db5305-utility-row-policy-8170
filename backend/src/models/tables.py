from sqlalchemy import (JSON, Column, ForeignKey, Integer, MetaData, String,
                        Table, Text)

schema = MetaData()
users = Table('accounts', schema,
    Column('id', Integer, primary_key=True),
    Column('username', String(40), nullable=False, unique=True),
    Column('password_hash', String(200), nullable=False),
    Column('role', String(20), nullable=False),
    Column('zone', String(20)))
cases = Table('business_cases', schema,
    Column('id', Integer, primary_key=True),
    Column('slug', String(64), nullable=False, unique=True),
    Column('title', String(120), nullable=False),
    Column('payload', JSON, nullable=False),
    Column('author', String(40), nullable=False),
    Column('created_at', String(32), nullable=False))
runs = Table('business_runs', schema,
    Column('id', Integer, primary_key=True),
    Column('case_id', ForeignKey('business_cases.id'), nullable=False, index=True),
    Column('status', String(20), nullable=False, index=True),
    Column('owner', String(40), nullable=False),
    Column('attempt_token', String(36)),
    Column('started_at', String(32)),
    Column('finished_at', String(32)),
    Column('created_at', String(32), nullable=False),
    Column('error', Text))
evidence = Table('business_evidence', schema,
    Column('id', Integer, primary_key=True),
    Column('run_id', ForeignKey('business_runs.id'), nullable=False, unique=True),
    Column('report', JSON, nullable=False),
    Column('digest', String(64), nullable=False),
    Column('reviewer', String(40)),
    Column('review_note', String(500)),
    Column('reviewed_at', String(32)))
audit = Table('audit_events', schema,
    Column('id', Integer, primary_key=True),
    Column('actor', String(40), nullable=False),
    Column('action', String(32), nullable=False),
    Column('reference', String(50), nullable=False),
    Column('created_at', String(32), nullable=False))
# 整改派单：一条差异（人员|工单|判定）一次生命周期一行，关闭不复活，再出现时另起新行并递增代次。
# open_key 在未关闭时等于 difference_key、关闭时置空，唯一约束保证同一差异同时最多一条未关闭派单，
# 因此签署重试或并发对账都不会重复派单。
dispatches = Table('rectification_dispatches', schema,
    Column('id', Integer, primary_key=True),
    Column('difference_key', String(130), nullable=False, index=True),
    Column('open_key', String(130), unique=True),
    Column('operator_id', String(40), nullable=False),
    Column('order_id', String(40), nullable=False),
    Column('zone', String(20), nullable=False, index=True),
    Column('utility', String(10), nullable=False),
    Column('kind', String(20), nullable=False),
    Column('generation', Integer, nullable=False),
    Column('status', String(20), nullable=False, index=True),
    Column('source_evidence_id', ForeignKey('business_evidence.id'), nullable=False),
    Column('last_seen_evidence_id', ForeignKey('business_evidence.id'), nullable=False),
    Column('opened_at', String(32), nullable=False),
    Column('acked_by', String(40)),
    Column('acked_at', String(32)),
    Column('ack_note', String(500)),
    Column('closed_by_evidence_id', ForeignKey('business_evidence.id')),
    Column('closed_at', String(32)))
# 交接事件：派单开出、区线回执、复验撤下各记一行，seq 全局单调递增，是区线断网续传的游标。
handovers = Table('handover_events', schema,
    Column('seq', Integer, primary_key=True),
    Column('dispatch_id', ForeignKey('rectification_dispatches.id'), nullable=False, index=True),
    Column('difference_key', String(130), nullable=False),
    Column('zone', String(20), nullable=False, index=True),
    Column('kind', String(20), nullable=False),
    Column('operator_id', String(40), nullable=False),
    Column('order_id', String(40), nullable=False),
    Column('generation', Integer, nullable=False),
    Column('event', String(20), nullable=False),
    Column('actor', String(40), nullable=False),
    Column('evidence_id', ForeignKey('business_evidence.id')),
    Column('note', String(500)),
    Column('created_at', String(32), nullable=False))
